class DukaRunner(Protocol):
    """Adapter contract for invoking the installed duka package."""

    def download(
        self,
        symbol: str,
        start_date: date,
        end_date: date,
        timeframe: str,
        destination: Path,
        timeout_seconds: float,
        threads: int,
        include_header: bool,
    ) -> Path:
        """Download M1 candles and return duka's generated CSV path."""
        ...


class DukaCommandRunner:
    """Invoke duka through its supported Python module entry point."""

    def download(
        self,
        symbol: str,
        start_date: date,
        end_date: date,
        timeframe: str,
        destination: Path,
        timeout_seconds: float,
        threads: int,
        include_header: bool,
    ) -> Path:
        """Run duka for one symbol and date partition.

        Args:
            symbol: Dukascopy instrument identifier.
            start_date: Inclusive download start date.
            end_date: Inclusive download end date.
            timeframe: Candle timeframe passed to duka.
            destination: Temporary output directory.
            timeout_seconds: Maximum process runtime.
            threads: Worker count passed to duka.
            include_header: Whether duka should emit a CSV header.

        Returns:
            The CSV generated by duka.

        Raises:
            HistoricalDownloadError: If duka fails or produces no CSV.
        """
        command = [
            sys.executable,
            "-m",
            "duka.main",
            symbol,
            "-s",
            start_date.isoformat(),
            "-e",
            end_date.isoformat(),
            "-c",
            timeframe,
            "-f",
            str(destination),
            "-t",
            str(threads),
        ]
        if include_header:
            command.append("--header")
        try:
            completed = subprocess.run(
                command,
                check=False,
                capture_output=True,
                text=True,
                timeout=timeout_seconds,
            )
        except subprocess.TimeoutExpired as exc:
            raise HistoricalDownloadError(
                f"duka timed out downloading {symbol}"
            ) from exc
        if completed.returncode != 0:
            detail = completed.stderr.strip() or completed.stdout.strip()
            raise HistoricalDownloadError(
                f"duka failed for {symbol} with exit code "
                f"{completed.returncode}: {detail}"
            )
        candidates = sorted(destination.glob("*.csv"))
        if not candidates:
            raise HistoricalDownloadError(
                f"duka produced no CSV for {symbol}; ensure duka is installed"
            )
        return candidates[-1]


class HistoricalDownloader:
    """Download resumable yearly M1 partitions using a Dukascopy adapter.

    Flow:
        DukascopyAdapter.fetch_bars → merge → HistoricalStorage.write_year
    """

    def __init__(
        self,
        config: HistoricalDataConfig | None = None,
        runner: DukaRunner | None = None,
        storage: HistoricalStorage | None = None,
        parser: HistoricalDataParser | None = None,
        sleeper: Callable[[float], None] = time.sleep,
        adapter: DukascopyAdapter | None = None,
    ) -> None:
        """Initialize the downloader.

        Args:
            config: Settings, or ``None`` to load the default JSON file.
            runner: Injectable duka process adapter (used when ``adapter`` is None).
            storage: Injectable yearly storage.
            parser: Injectable strict CSV parser (used when ``adapter`` is None).
            sleeper: Retry-delay function, injectable for tests.
            adapter: Optional pre-built DukascopyAdapter.
        """
        self.config = config or load_historical_config()
        self.runner = runner or DukaCommandRunner()
        self.storage = storage or HistoricalStorage(self.config.data_directory)
        self.parser = parser or HistoricalDataParser()
        self._sleep = sleeper
        self._logger = setup_logger("historical_downloader")
        self.adapter = adapter or DukascopyAdapter(
            runner=self.runner,
            parser=self.parser,
            timeout_seconds=self.config.timeout_seconds,
            threads=self.config.duka_threads,
            include_header=self.config.include_header,
            supported_timeframe=self.config.timeframe,
        )

    def download(
        self,
        symbols: Sequence[str] | None = None,
        start_date: date | None = None,
        end_date: date | None = None,
    ) -> tuple[Path, ...]:
        """Download configured M1 data into atomic yearly partitions.

        Args:
            symbols: Symbols to download, defaulting to configuration.
            start_date: Inclusive start, defaulting to configuration.
            end_date: Inclusive end, defaulting to configuration.

        Returns:
            Paths downloaded or skipped during this operation.

        Raises:
            HistoricalDownloadError: If validation or all retries fail.
        """
        requested_symbols = tuple(
            symbol.upper() for symbol in (symbols or self.config.symbols)
        )
        requested_start = start_date or self.config.start_date
        requested_end = end_date or self.config.end_date
        if requested_start > requested_end:
            raise HistoricalDownloadError("start_date cannot be after end_date")
        unknown = sorted(set(requested_symbols) - set(self.config.symbols))
        if unknown:
            raise HistoricalDownloadError(
                f"Symbols are not configured: {', '.join(unknown)}"
            )

        paths: list[Path] = []
        for symbol in requested_symbols:
            for year in range(requested_start.year, requested_end.year + 1):
                partition_start = max(requested_start, date(year, 1, 1))
                partition_end = min(requested_end, date(year, 12, 31))
                path = self.storage.year_path(symbol, self.config.timeframe, year)
                if (
                    not self.config.overwrite_existing_files
                    and self.storage.has_coverage(
                        symbol,
                        self.config.timeframe,
                        partition_start,
                        partition_end,
                    )
                ):
                    self._logger.info("Skipping existing historical data: %s", path)
                    paths.append(path)
                    continue
                paths.append(
                    self._download_partition(
                        symbol, year, partition_start, partition_end
                    )
                )
        return tuple(paths)

    def _download_partition(
        self, symbol: str, year: int, start_date: date, end_date: date
    ) -> Path:
        attempts = self.config.retries + 1
        for attempt in range(1, attempts + 1):
            try:
                self._logger.info(
                    "Downloading %s %s %s to %s (attempt %s/%s)",
                    symbol,
                    self.config.timeframe,
                    start_date,
                    end_date,
                    attempt,
                    attempts,
                )
                downloaded = self.adapter.fetch_bars(
                    symbol,
                    self.config.timeframe,
                    start_date,
                    end_date,
                )
                bars, coverage_start, coverage_end = self._merge_existing(
                    symbol, year, downloaded, start_date, end_date
                )
                report = assess_dataset_quality(
                    bars,
                    instrument=symbol,
                    timeframe=self.config.timeframe,
                    provider=self.adapter.provider_id,
                    coverage_start=coverage_start,
                    coverage_end=coverage_end,
                    expected_step_minutes=1,
                )
                self._logger.info(
                    "Ingest quality %s %s %s: bars=%s duplicates=%s invalid=%s gaps=%s",
                    symbol,
                    self.config.timeframe,
                    year,
                    report.bar_count,
                    report.duplicate_count,
                    report.invalid_bar_count,
                    report.timestamp_gap_count,
                )
                return self.storage.write_year(
                    symbol,
                    self.config.timeframe,
                    year,
                    bars,
                    coverage_start,
                    coverage_end,
                    provider=self.adapter.provider_id,
                    bar_count=len(bars),
                )
            except Exception as exc:
                if attempt == attempts:
                    raise HistoricalDownloadError(
                        f"Unable to download {symbol} {self.config.timeframe} "
                        f"for {year} after "
                        f"{attempts} attempts"
                    ) from exc
                self._logger.warning(
                    "Historical download failed; retrying: %s", exc
                )
                self._sleep(self.config.retry_delay_seconds)
        raise AssertionError("unreachable")

    def _merge_existing(
        self,
        symbol: str,
        year: int,
        downloaded: list[Bar],
        start_date: date,
        end_date: date,
    ) -> tuple[list[Bar], date, date]:
        path = self.storage.year_path(symbol, self.config.timeframe, year)
        if self.config.overwrite_existing_files or not path.exists():
            return downloaded, start_date, end_date
        existing = self.parser.parse_file(path, symbol)
        merged = {bar.timestamp: bar for bar in existing}
        merged.update({bar.timestamp: bar for bar in downloaded})
        coverage = self.storage.coverage(symbol, self.config.timeframe, year)
        if coverage is None:
            return list(merged.values()), date(year, 1, 1), date(year, 12, 31)
        return (
            list(merged.values()),
            min(coverage[0], start_date),
            max(coverage[1], end_date),
        )


def main() -> None:
    """Download all symbols and dates defined in historical configuration."""
    HistoricalDownloader().download()


if __name__ == "__main__":
    main()
